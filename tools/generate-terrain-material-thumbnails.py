#!/usr/bin/env python3
"""Register the 82 supplied material thumbnails in the production icon atlas.

The catalog order defines stable material-000..081 names. Source thumbnails
remain untouched; pack-icon-atlas.py derives only its existing 96 px UI cells.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

from ui_asset_format import cpp_identifier
from generated_output import write_text_if_changed


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    library = root / "assets/terrain/library"
    named = root / "assets/astra-visual/icons/named"
    catalog_path = named / "catalog.json"
    materials = json.loads((library / "catalog.json").read_text(encoding="utf-8"))
    entries = materials["materials"]
    if len(entries) != 82 or len({entry["id"] for entry in entries}) != 82:
        raise ValueError("Expected exactly 82 distinct material IDs in supplied catalog order")
    textures = {texture["id"]: texture for texture in materials["textures"]}
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    prefix = "zz-terrain-material/"
    expected = {f"{prefix}material-{index:03}" for index in range(82)}
    stale = {name for name in catalog["icons"] if name.startswith(prefix)} - expected
    if stale:
        raise ValueError(f"Unexpected existing material icon names: {sorted(stale)}")
    header = [
        "// Generated by tools/generate-terrain-material-thumbnails.py; do not edit.",
        '#pragma once', '#include "ui/ui_icon_id.h"', '#include <string_view>',
        "namespace ae::editor {",
        "inline ui::UiIcon terrainMaterialIcon(std::string_view sourceCatalogId) {",
    ]
    originals: dict[Path, str] = {}
    for index, material in enumerate(entries):
        name = f"{prefix}material-{index:03}"
        maps = material.get("resolved_maps") or material.get("maps") or {}
        texture = textures[maps["albedo"]["texture"]]
        source = (library / texture["thumbnail"]).resolve(strict=True)
        if library.resolve() not in source.parents or source.suffix.lower() != ".png":
            raise ValueError(f"Invalid thumbnail path for {material['id']}")
        originals[source] = hashlib.sha256(source.read_bytes()).hexdigest()
        metadata = {
            "category": "zz-terrain-material",
            "name": f"material-{index:03}",
            "label": material["name"],
            "raster": Path(os.path.relpath(source, named)).as_posix(),
            "dark_ui_ready": True,
            "force_opaque": True,
            "source_catalog_id": material["id"],
        }
        old = catalog["icons"].get(name)
        if old and old.get("source_catalog_id") != material["id"]:
            raise ValueError(f"Catalog order changed stable mapping {name}")
        catalog["icons"][name] = metadata
        header.append(f'  if(sourceCatalogId=={json.dumps(material["id"])})return ui::UiIcon::{cpp_identifier(name)};')
    header.extend(["  return ui::UiIcon::AssetsMaterial;", "}", "}", ""])
    enum_path = root / "native/ui/ui_icon_id.h"
    previous = dict(re.findall(r"\s+(\w+) = (\d+),", enum_path.read_text(encoding="utf-8")))
    write_text_if_changed(catalog_path, json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")
    write_text_if_changed(root / "native/editor/terrain_material_icons.h", "\n".join(header))
    subprocess.run([sys.executable, str(root / "tools/pack-icon-atlas.py")], cwd=root, check=True)
    current = dict(re.findall(r"\s+(\w+) = (\d+),", enum_path.read_text(encoding="utf-8")))
    for name, value in previous.items():
        if name not in ("BrandWordmark", "BrandMark") and current.get(name) != value:
            raise ValueError(f"Existing icon ID changed: {name}")
    for source, digest in originals.items():
        if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Original thumbnail changed: {source}")
    print(f"82 material mappings packed; {len(originals)} original thumbnails unchanged; prior icon IDs preserved.")


if __name__ == "__main__":
    main()
