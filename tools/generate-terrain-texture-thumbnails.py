#!/usr/bin/env python3
"""Register real texture thumbnails in the UI atlas; preserve source bytes and IDs."""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import sys
from generated_output import write_text_if_changed
from ui_asset_format import cpp_identifier
ROOT=Path(__file__).resolve().parents[1]

def main():
    library=ROOT/'assets/terrain/library'
    named=ROOT/'assets/astra-visual/icons/named'
    assets=json.loads((library/'catalog.json').read_text(encoding='utf-8'))['textures']
    if len({asset['id'] for asset in assets})!=len(assets):
        raise ValueError('Texture catalog IDs must be unique')
    path=named/'catalog.json';catalog=json.loads(path.read_text(encoding='utf-8'))
    prefix='zzz-terrain-texture/'
    expected={f'{prefix}texture-{i:03}' for i in range(len(assets))}
    if {name for name in catalog['icons'] if name.startswith(prefix)}-expected:
        raise ValueError('Registered texture catalog order cannot be removed silently')
    header=['// Generated by tools/generate-terrain-texture-thumbnails.py; do not edit.',
        '#pragma once','#include "ui/ui_icon_id.h"','#include <string_view>',
        'namespace ae::editor {',
        'inline ui::UiIcon terrainTextureIcon(std::string_view sourceCatalogId) {']
    originals={}
    for index,asset in enumerate(assets):
        name=f'{prefix}texture-{index:03}'
        source=(library/asset['thumbnail']).resolve(strict=True)
        if library.resolve() not in source.parents or source.suffix.lower()!='.png':
            raise ValueError('Invalid texture thumbnail path')
        originals[source]=hashlib.sha256(source.read_bytes()).hexdigest()
        old=catalog['icons'].get(name)
        if old and old.get('source_catalog_id')!=asset['id']:
            raise ValueError(f'Texture order changed stable mapping {name}')
        catalog['icons'][name]={'category':'zzz-terrain-texture','name':f'texture-{index:03}',
            'label':Path(asset['source_path']).stem,'raster':Path(os.path.relpath(source,named)).as_posix(),
            'dark_ui_ready':True,'force_opaque':True,'append_after_brand':True,
            'source_catalog_id':asset['id'],'generator':'tools/generate-terrain-texture-thumbnails.py'}
        header.append(f'  if(sourceCatalogId=={json.dumps(asset["id"])})return ui::UiIcon::{cpp_identifier(name)};')
    header+=['  return ui::UiIcon::AssetsTexture;','}','}','']
    enum=ROOT/'native/ui/ui_icon_id.h'
    before=dict(re.findall(r'\s+(\w+) = (\d+),',enum.read_text(encoding='utf-8')))
    write_text_if_changed(path,json.dumps(catalog,ensure_ascii=False,indent=2)+'\n')
    write_text_if_changed(ROOT/'native/editor/terrain_texture_icons.h','\n'.join(header))
    subprocess.run([sys.executable,str(ROOT/'tools/pack-icon-atlas.py')],cwd=ROOT,check=True)
    after=dict(re.findall(r'\s+(\w+) = (\d+),',enum.read_text(encoding='utf-8')))
    for name,value in before.items():
        if after.get(name)!=value:raise ValueError(f'Existing icon ID changed: {name}')
    for source,digest in originals.items():
        if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:raise ValueError('Source thumbnail modified')
    print(f'{len(assets)} real texture thumbnails packed; every previous icon ID and source thumbnail preserved.')
if __name__=='__main__':main()
