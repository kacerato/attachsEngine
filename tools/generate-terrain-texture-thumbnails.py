#!/usr/bin/env python3
"""Register thumbnails by source identity; append after every published name."""
from pathlib import Path
import argparse,hashlib,json,os,re,subprocess,sys
from generated_output import write_text_if_changed
from ui_asset_format import cpp_identifier
ROOT=Path(__file__).resolve().parents[1]
GENERATOR='tools/generate-terrain-texture-thumbnails.py'
def plan(root):
 library=root/'assets/terrain/library';named=root/'assets/astra-visual/icons/named'
 assets=json.loads((library/'catalog.json').read_text(encoding='utf-8'))['textures']
 ids=[a['id'] for a in assets]
 if len(set(ids))!=len(ids):raise ValueError('Texture catalog IDs must be unique')
 catalog=json.loads((named/'catalog.json').read_text(encoding='utf-8'));registered={}
 for name,meta in catalog['icons'].items():
  if meta.get('generator')==GENERATOR:
   identity=meta.get('source_catalog_id')
   if identity not in ids or identity in registered:raise ValueError('Registered texture identity removed or duplicated')
   registered[identity]=name
 maximum=max(catalog['icons'],default='');append_prefix=None
 header=['// Generated by '+GENERATOR+'; do not edit.','#pragma once','#include "ui/ui_icon_id.h"','#include <string_view>','namespace ae::editor {','inline ui::UiIcon terrainTextureIcon(std::string_view sourceCatalogId) {']
 originals={};mapping={}
 for index,asset in enumerate(assets):
  name=registered.get(asset['id'])
  if name is None:
   if append_prefix is None:
    append_prefix='zzzzz-terrain-texture'
    if maximum>=append_prefix+'/':
     leading=max((len(n)-len(n.lstrip('z')) for n in catalog['icons']),default=4)
     append_prefix='z'*(leading+1)+'-terrain-texture'
   name=f'{append_prefix}/texture-{index:03}'
   if name in catalog['icons'] or name<=maximum:raise ValueError('New texture name must append after published names')
  source=(library/asset['thumbnail']).resolve(strict=True)
  if not source.is_relative_to(library.resolve()) or source.suffix.lower()!='.png':raise ValueError('Invalid texture thumbnail path')
  originals[source]=hashlib.sha256(source.read_bytes()).hexdigest()
  category,leaf=name.split('/',1);old=catalog['icons'].get(name)
  if old and old.get('source_catalog_id')!=asset['id']:raise ValueError('Texture identity mapping conflicts')
  catalog['icons'][name]={'category':category,'name':leaf,'label':Path(asset['source_path']).stem,
   'raster':Path(os.path.relpath(source,named)).as_posix(),'dark_ui_ready':True,'force_opaque':True,
   'append_after_brand':True,'source_catalog_id':asset['id'],'generator':GENERATOR}
  mapping[asset['id']]=name
  header.append(f'  if(sourceCatalogId=={json.dumps(asset["id"])})return ui::UiIcon::{cpp_identifier(name)};')
 header+=['  return ui::UiIcon::AssetsTexture;','}','}','']
 return catalog,'\n'.join(header),originals,mapping
def prepare(root,pack=True):
 catalog,header,originals,mapping=plan(root);enum=root/'native/ui/ui_icon_id.h'
 published=enum.read_text(encoding='utf-8')
 before=dict(re.findall(r'\s+(\w+) = (\d+),',published))
 # Mirror the packer's logical order before writing any output. Brand IDs are
 # inserted between regular and explicitly appended entries, never sorted away.
 ordered=sorted(catalog['icons'])+['brand/wordmark','brand/mark']
 appended={name for name,meta in catalog['icons'].items() if meta.get('append_after_brand',False)}
 ordered=[name for name in ordered if name not in appended]+[name for name in ordered if name in appended]
 predicted={cpp_identifier(name):str(index) for index,name in enumerate(ordered,1)}
 for name,value in before.items():
  if name!='None' and predicted.get(name)!=value:raise ValueError('Published icon ordering conflict before publication: '+name)
 write_text_if_changed(root/'assets/astra-visual/icons/named/catalog.json',json.dumps(catalog,ensure_ascii=False,indent=2)+'\n')
 write_text_if_changed(root/'native/editor/terrain_texture_icons.h',header)
 if pack:
  subprocess.run([sys.executable,str(root/'tools/pack-icon-atlas.py')],cwd=root,check=True)
  after=dict(re.findall(r'\s+(\w+) = (\d+),',enum.read_text(encoding='utf-8')))
  for name,value in before.items():
   if after.get(name)!=value:raise ValueError(f'Existing icon ID changed: {name}')
 for source,digest in originals.items():
  if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:raise ValueError('Source thumbnail modified')
 return mapping
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--root',type=Path,default=ROOT);parser.add_argument('--no-pack',action='store_true');args=parser.parse_args()
 mapping=prepare(args.root.resolve(),not args.no_pack);print(f'{len(mapping)} real texture thumbnails registered by stable source identity.')
if __name__=='__main__':main()
