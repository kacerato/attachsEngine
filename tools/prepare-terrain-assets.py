"""Prepare supplied Path Painter textures and Astra terrain icons reproducibly."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1]
source = root / 'build/terrain-packages/Path Painter II v2.1.10/Assets/3D Haven/Path Painter II/Editor/Demo/Terrains/FFT-F/Terrain Layers/Textures'
output = root / 'assets/terrain'
output.mkdir(parents=True, exist_ok=True)
files = ['3DH FTT Grass_002 Grass_001a 2K.png', '3DH FTT Cliff_001 4K.png', '3DH FTT Dirt_002a 1K.png', '3DH FTT Path_001 2K.png']
manifest = []
code = ['// Generated by tools/prepare-terrain-assets.py. Supplied Path Painter textures.\n#pragma once\nnamespace ae::resources {']
for index, name in enumerate(files):
    path = source / name
    dest = output / f'layer-{index}.png'
    Image.open(path).convert('RGB').resize((256, 256), Image.Resampling.LANCZOS).save(dest, optimize=True)
    data = dest.read_bytes()
    code.append(f'inline constexpr unsigned char terrainTexture{index}[] = {{' + ','.join(map(str, data)) + '};')
    manifest.append(dict(layer=index, source=name, package='Path Painter II v2.1.10', source_sha256=hashlib.sha256(path.read_bytes()).hexdigest(), output=dest.name, sha256=hashlib.sha256(data).hexdigest(), conversion='RGB PNG, 256x256 Lanczos'))
code.append('}')
(root/'native/resources/terrain_textures.generated.h').write_text('\n'.join(code)+'\n', encoding='utf-8')
(output/'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
license_path = Path.home()/'Downloads/plugins/licença.txt'
(output/'LICENSE-supplied.txt').write_bytes(license_path.read_bytes())
icons = root/'assets/astra-visual/icons'
catalog_path = icons/'named/catalog.json'
catalog = json.loads(catalog_path.read_text(encoding='utf-8'))
shapes = {
    'terrain': [[(8,76),(29,31),(43,50),(61,17),(88,76),(8,76)],[(20,58),(35,62),(53,48),(76,57)]],
    'voxel': [[(14,33),(48,14),(82,33),(82,70),(48,88),(14,70),(14,33)],[(14,33),(48,52),(82,33)],[(48,52),(48,88)],[(31,23),(65,42),(65,79)],[(31,42),(31,79)]],
    'sculpt': [[(12,77),(28,65),(43,70),(57,55),(84,62)],[(26,46),(58,14),(74,30),(42,62),(26,46)],[(26,46),(20,66),(42,62)]],
    'layers': [[(10,30),(48,12),(86,30),(48,48),(10,30)],[(10,48),(48,66),(86,48)],[(10,66),(48,84),(86,66)]]}
for name, lines in shapes.items():
    image=Image.new('RGBA',(384,384)); draw=ImageDraw.Draw(image)
    for points in lines: draw.line([(x*4,y*4) for x,y in points], fill=(20,20,20,255), width=16, joint='curve')
    dest=icons/'named/terrain';dest.mkdir(exist_ok=True)
    image.resize((96,96),Image.Resampling.LANCZOS).save(dest/f'{name}.png')
    dest=icons/'vector/terrain';dest.mkdir(parents=True,exist_ok=True)
    polylines=''.join('<polyline points="'+' '.join(f'{x},{y}' for x,y in p)+'"/>' for p in lines)
    (dest/f'{name}.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96"><g fill="none" stroke="#141414" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">'+polylines+'</g></svg>',encoding='utf-8')
    catalog['icons']['terrain/'+name]={'source':'vector/terrain/'+name+'.svg'}
catalog_path.write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Prepared four textures and four terrain icons.')
